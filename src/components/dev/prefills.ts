// Derived presets from the live-like dump
// Minimal: keep only PRSice as selected tool and trim populations/dataset
// Transitional: keep PRSice + BridgePRS with partial mappings
// Full: identical to LIVE_DUMMY_PREFILLS

type Prefill = typeof LIVE_DUMMY_PREFILLS

const pick = <T extends object, K extends keyof T>(
  obj: T,
  keys: K[]
): Pick<T, K> => {
  const out = {} as Pick<T, K>
  keys.forEach((k) => ((out as any)[k] = obj[k]))
  return out
}

const trimDatasetStructure = (base: Prefill["datasetStructure"]) => {
  const dirs = base.directories.filter((d) =>
    ["h3gwas_data", "geno", "AFR"].includes(d.name)
  )
  const files = base.files.filter((f) =>
    ["AFR_sumstats.txt", "chr1.bed", "chr1.bim", "chr1.fam"].includes(f.name)
  )
  return {
    ...base,
    directories: dirs,
    files,
    total_files: files.length,
    total_directories: dirs.length,
  }
}

